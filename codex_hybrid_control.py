    def activate_api(self):
        typed_token = self.token_var.get().strip()
        saved_token = get_user_api_key()
        token = typed_token or saved_token
        replacing = bool(typed_token and saved_token and typed_token != saved_token)
        repairing = bool(not typed_token and saved_token)

        if not token:
            messagebox.showwarning(APP_TITLE, "Сначала вставь API-токен. Сохранённого активного токена сейчас нет.")
            return

        if repairing:
            prompt = (
                "Восстановить/проверить API-настройку, используя уже активированный USER-токен Windows?\n\n"
                "Сохранённый токен будет проверен внутри приложения, но НЕ будет показан, скопирован в файлы приложения или записан в логи."
            )
        elif replacing:
            prompt = (
                "Проверить токен из поля и ЗАМЕНИТЬ текущий активированный USER-токен Windows?\n\n"
                "Токен не будет записан в config.toml, профили, логи или state-файл приложения."
            )
        else:
            prompt = (
                "Проверить этот токен через настроенный gateway и сохранить его как USER-переменную Windows FUNPAY_API_KEY?\n\n"
                "Токен не будет записан в config.toml, профили, логи или state-файл приложения."
            )

        if not messagebox.askyesno(APP_TITLE, prompt):
            return

        def job():
            info = validate_api_key(token)
            if typed_token:
                set_user_api_key(token)
            bootstrap_codex_files()
            catalog_error = None
            count = 0
            try:
                count, _ = download_catalog()
            except Exception as e:
                catalog_error = str(e)
            # Explicit API activation/repair should also migrate stale Hybrid
            # Control worker profiles instead of merely reporting them as 0/3.
            repair_worker_profiles(codex_dir(), default_catalog_path())
            return info, count, catalog_error

        def done(result):
            info, count, catalog_error = result
            self.token_var.set("")
            quota = info.get("quota") if isinstance(info, dict) else None
            remaining = quota.get("remaining") if isinstance(quota, dict) else None
            extra = f" · осталось: {remaining:,}" if isinstance(remaining, (int, float)) else ""
            action = "восстановлена" if repairing else ("заменена и активирована" if replacing else "активирована")
            if catalog_error:
                self.status.set(f"API-настройка {action}{extra}. Не удалось обновить каталог: {catalog_error}")
                messagebox.showwarning(
                    APP_TITLE,
                    "API-настройка активна, но живой каталог моделей обновить не удалось. Локальный резервный каталог остаётся доступен.\n\n" + catalog_error,
                )
            else:
                self.status.set(f"API-настройка {action}{extra} · моделей: {count} · профили воркеров готовы")
                messagebox.showinfo(
                    APP_TITLE,
                    f"API-настройка успешно {action}.\n\nПрофили Opus/Astra/Luna автоматически мигрированы к безопасной конфигурации.\nЗначение токена нигде в интерфейсе или файлах приложения не показывалось.",
                )
            self.refresh_api_usage_async()

        action_text = "Восстановление API-настройки по сохранённому токену..." if repairing else "Проверка токена и подготовка API-настройки..."
        self._run_background(action_text, job, done)

