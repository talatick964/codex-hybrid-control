def extract_model_ids(data) -> list[str]:
    ids: list[str] = []

    def add(v):
        if isinstance(v, str) and v.strip() and v.strip() not in ids:
            ids.append(v.strip())

    def walk(obj):
        if isinstance(obj, dict):
            for key in ("slug", "id", "model", "name"):
                if key in obj:
                    val = obj[key]
                    if isinstance(val, str) and (key in {'id','model','slug'} or "-" in val or "/" in val):
                        add(val)
                        return
            for v in obj.values():
                walk(v)
        elif isinstance(obj, list):
            for item in obj:
                walk(item)

    walk(data)
    return ids


