def _parse_worker_log(log: Path) -> dict:
    out = {"thread_id": None, "last_message": "", "last_error": "", "terminal_status": None, "tools": []}
    try:
        with log.open("r", encoding="utf-8", errors="ignore") as fh:
            for line in fh:
                try:
                    ev = json.loads(line)
                except Exception:
                    continue
                event_type = str(ev.get("type") or "")
                if event_type == "thread.started":
                    out["thread_id"] = ev.get("thread_id") or out["thread_id"]
                elif event_type == "turn.completed":
                    out["terminal_status"] = "EXITED"
                elif event_type in {"turn.failed", "error"}:
                    out["terminal_status"] = "FAILED"
                    out["last_error"] = str(ev.get("error") or ev.get("message") or ev)[-2000:]
                item = ev.get("item") if isinstance(ev.get("item"), dict) else {}
                item_type = str(item.get("type") or "")
                if event_type == "item.completed" and item_type == "agent_message":
                    txt = sanitize_agent_text(str(item.get("text") or ""))
                    if txt:
                        out["last_message"] = txt[-1000:]
                if item_type in {"tool_call", "command_execution", "mcp_tool_call"} and item.get("name"):
                    out["tools"].append(str(item.get("name")))
                if item.get("calls"):
                    for call in item.get("calls") or []:
                        if isinstance(call, dict) and call.get("name"):
                            out["tools"].append(str(call.get("name")))
    except Exception:
        pass
    return out


def _worker_elapsed_seconds(row: dict) -> float:
    try:
        started = datetime.fromisoformat(str(row.get("started_at") or ""))
        finished = datetime.fromisoformat(row['finished_at']) if row.get('finished_at') else datetime.now(started.tzinfo)
        return max(0.0, (finished - started).total_seconds())
    except Exception:
        return 0.0


def _worker_registry_transaction(fn):
    @wraps(fn)
    def wrapped(*args, **kwargs):
        with file_transaction(worker_registry_path().with_suffix('.lock')):
            return fn(*args, **kwargs)
    return wrapped


@_worker_registry_transaction
def refresh_worker_registry() -> list[dict]:
    rows = _load_workers()
    changed = False
    for row in rows:
        outcome = read_json(Path(row['result_path']), {}) if row.get('result_path') else {}
        if outcome and row.get('status') in {'RUNNING', 'EXITED'}:
            row['status'] = outcome.get('status', 'FAILED')
            row['last_error'] = outcome.get('error', '')
            row['finished_at'] = row.get('finished_at') or now_iso()
            changed = True
        if row.get("status") == "RUNNING" and not pid_alive(int(row.get("pid") or 0)):
            row["status"] = "EXITED"
            row["finished_at"] = row.get("finished_at") or now_iso()
            changed = True
        if row.get("status") == "RUNNING":
            limit = int(row.get("timeout_seconds") or 0)
            if limit and _worker_elapsed_seconds(row) > limit:
                if stop_worker(row.get("id", "")):
                    row["status"] = "TIMED_OUT"
                    row["finished_at"] = now_iso()
                    row["last_error"] = "Истёк лимит времени API-агента. Процесс остановлен."
                else:
                    row['last_error'] = 'Не удалось подтвердить остановку процесса после таймаута.'
                changed = True
        log = Path(row.get("log", "")) if row.get("log") else None
        if log and log.exists():
            parsed = _parse_worker_log(log)
            if parsed["thread_id"] != row.get("thread_id"):
                row["thread_id"] = parsed["thread_id"]
                changed = True
            if parsed["last_message"] != row.get("last_message", ""):
                row["last_message"] = parsed["last_message"]
                changed = True
            if parsed["last_error"] and parsed["last_error"] != row.get("last_error", ""):
                row["last_error"] = parsed["last_error"]
                changed = True
            if parsed["terminal_status"] and row.get("status") in {"RUNNING", "EXITED"}:
                row["status"] = parsed["terminal_status"]
                row["finished_at"] = row.get("finished_at") or now_iso()
                changed = True
            if row.get('status') == 'EXITED' and (not parsed['terminal_status'] or not parsed['last_message']):
                row['status'] = 'INCOMPLETE'
                row['last_error'] = 'Процесс завершился без подтверждённого итогового ответа.'
                changed = True
    if changed:
        _save_workers(rows)
    return rows


@_worker_registry_transaction
def launch_api_worker(profile: str, project: Path, prompt: str, label: str = "", timeout_seconds: int = 900) -> dict:
    if is_stock_mode():
        raise RuntimeError("Hybrid Control отключён. Запуск API-агентов недоступен.")
    profile = profile.strip().lower()
    if profile not in WORKER_PROFILES:
        raise ValueError(f"Неизвестный профиль воркера: {profile}")
    if not project.exists() or not project.is_dir():
        raise ValueError("Папка проекта не существует")
    if not prompt.strip():
        raise ValueError("Инструкция воркера пуста")
    health = inspect_worker_profile(codex_dir(), profile)
    if not health.get("ready"):
        raise RuntimeError(
            f"Worker profile '{profile}' is not safe/ready ({health.get('reason')}). "
            "Run ACTIVATE / REPAIR API SETUP before launching it."
        )
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    worker_id = f"{profile}-{stamp}-{uuid.uuid4().hex[:6]}"
    log = logs_dir() / f"{worker_id}.jsonl"
    cmd = [codex_command(), "exec", "--sandbox", "workspace-write" if profile == "opus" else "read-only",
           "-c", 'approval_policy="never"', "--skip-git-repo-check", "--profile", profile, "--json", "-C", str(project), "--", prompt]
    timeout_seconds = max(30, min(int(timeout_seconds), 7200))
    result_path = log.with_suffix('.result.json')
    supervisor, supervisor_args = _self_command_for_worker_mcp()
    cmd = [supervisor] + [arg for arg in supervisor_args if arg != '--mcp-workers'] + [
        '--supervise-worker', str(timeout_seconds), str(result_path), '--'] + cmd
    flags = 0
    startup = None
    if os.name == "nt":
        flags = getattr(subprocess, "CREATE_NO_WINDOW", 0)
        startup = subprocess.STARTUPINFO()
        startup.dwFlags |= subprocess.STARTF_USESHOWWINDOW
        startup.wShowWindow = 0
    log_fh = log.open("w", encoding="utf-8", buffering=1)
    try:
        proc = subprocess.Popen(
            cmd,
            cwd=str(project),
            stdout=log_fh,
            stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL,
            creationflags=flags,
            startupinfo=startup,
            text=True,
        )
    except Exception:
        log_fh.close()
        raise
    log_fh.close()
    row = {
        "id": worker_id,
        "profile": profile,
        "model_selector": worker_settings()[profile]["model"],
        "label": label.strip() or prompt.strip().splitlines()[0][:120],
        "project": str(project),
        "pid": proc.pid,
        "pid_kind": "supervisor",
        "status": "RUNNING",
        "started_at": now_iso(),
        "finished_at": None,
        "timeout_seconds": max(30, min(int(timeout_seconds), 7200)),
        "log": str(log),
        "result_path": str(result_path),
        "thread_id": None,
        "last_message": "",
        "last_error": "",
    }
    rows = _load_workers()
    rows.append(row)
    _save_workers(rows)
    return row


@_worker_registry_transaction
def stop_worker(worker_id: str) -> bool:
    rows = _load_workers()
    target = next((x for x in rows if x.get("id") == worker_id), None)
    if not target:
        return False
    pid = int(target.get("pid") or 0)
    if pid_alive(pid):
        if os.name == "nt":
            result = subprocess.run(["taskkill", "/PID", str(pid), "/T", "/F"], capture_output=True, text=True,
                                    creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0),timeout=10)
            if result.returncode and pid_alive(pid):
                return False
        else:
            try:
                os.kill(pid, 15)
            except OSError:
                pass
    target["status"] = "STOPPED"
    target["finished_at"] = now_iso()
    _save_workers(rows)
    return True


