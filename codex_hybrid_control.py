def backup_config(config_path: Path) -> Path | None:
    if not config_path.exists():
        return None
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    backup_dir = config_path.parent / "hybrid_control_backups"
    backup_dir.mkdir(parents=True, exist_ok=True)
    dst = backup_dir / f"config-{stamp}.toml"
    shutil.copy2(config_path, dst)
    return dst


def cleanup_old_backups(config_path: Path, keep: int = 30) -> None:
    backup_dir = config_path.parent / "hybrid_control_backups"
    if not backup_dir.exists():
        return
    backups = sorted(backup_dir.glob("config-*.toml"), key=lambda p: p.stat().st_mtime, reverse=True)
    for path in backups[keep:]:
        try:
            path.unlink()
        except OSError:
            pass


