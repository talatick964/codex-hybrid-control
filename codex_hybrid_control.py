def ensure_provider_config(config_path: Path) -> tuple[bool, Path | None]:
    """Create missing config, or non-destructively ensure provider block exists."""
    config_path.parent.mkdir(parents=True, exist_ok=True)
    if not config_path.exists():
        text = minimal_config_text()
        validate_toml(text)
        write_text_atomic(config_path, text)
        return True, None

    original, has_bom = read_text_preserve_bom(config_path)
    validate_toml(original)
    updated = patch_table_keys(original, "model_providers.funpay", provider_values())
    if updated == original:
        return False, None
    validate_toml(updated)
    backup = backup_config(config_path)
    try:
        write_text_atomic(config_path, updated, has_bom)
        validate_toml(read_text_preserve_bom(config_path)[0])
    except Exception:
        if backup:
            shutil.copy2(backup, config_path)
        raise
    cleanup_old_backups(config_path)
    return True, backup


