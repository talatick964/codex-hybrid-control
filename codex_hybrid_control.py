def split_top_level_preamble(text: str) -> tuple[list[str], list[str]]:
    lines = text.splitlines(keepends=True)
    first_table = len(lines)
    for i, line in enumerate(lines):
        if re.match(r"^\s*\[", line):
            first_table = i
            break
    return lines[:first_table], lines[first_table:]


def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def edit_root_keys(text: str, set_values: dict[str, str], remove_keys: set[str] | None = None) -> str:
    remove_keys = remove_keys or set()
    preamble, rest = split_top_level_preamble(text)
    key_re = re.compile(r"^(\s*)([A-Za-z0-9_-]+)(\s*)=(.*?)(\r?\n)?$")
    seen: set[str] = set()
    out: list[str] = []

    for line in preamble:
        m = key_re.match(line)
        if not m:
            out.append(line)
            continue
        key = m.group(2)
        if key in remove_keys:
            continue
        if key in set_values:
            ending = m.group(5) or ("\r\n" if "\r\n" in text else "\n")
            out.append(f"{m.group(1)}{key}{m.group(3)}= {set_values[key]}{ending}")
            seen.add(key)
        else:
            out.append(line)

    newline = "\r\n" if "\r\n" in text else "\n"
    missing = [k for k in set_values if k not in seen]
    if missing:
        if out and out[-1].strip():
            out.append(newline)
        for key in missing:
            out.append(f"{key} = {set_values[key]}{newline}")
        if rest and (not out or out[-1].strip()):
            out.append(newline)

    return "".join(out + rest)


def patch_table_keys(text: str, table: str, set_values: dict[str, str]) -> str:
    """Patch keys inside a TOML table while preserving unknown keys/comments."""
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = text.splitlines(keepends=True)
    header_re = re.compile(r"^\s*\[" + re.escape(table) + r"\]\s*(?:#.*)?(?:\r?\n)?$")
    any_header_re = re.compile(r"^\s*\[")
    start = next((i for i, line in enumerate(lines) if header_re.match(line)), None)

    if start is None:
        out = text
        if out and not out.endswith(("\n", "\r")):
            out += newline
        if out and out.strip():
            out += newline
        out += f"[{table}]{newline}"
        for key, value in set_values.items():
            out += f"{key} = {value}{newline}"
        return out

    end = len(lines)
    for i in range(start + 1, len(lines)):
        if any_header_re.match(lines[i]):
            end = i
            break

    key_re = re.compile(r"^(\s*)([A-Za-z0-9_-]+)(\s*)=(.*?)(\r?\n)?$")
    seen: set[str] = set()
    block = [lines[start]]
    for line in lines[start + 1:end]:
        m = key_re.match(line)
        if m and m.group(2) in set_values:
            key = m.group(2)
            ending = m.group(5) or newline
            block.append(f"{m.group(1)}{key}{m.group(3)}= {set_values[key]}{ending}")
            seen.add(key)
        else:
            block.append(line)

    missing = [k for k in set_values if k not in seen]
    if missing:
        if block and block[-1].strip() == "":
            insert_at = len(block) - 1
            additions = [f"{k} = {set_values[k]}{newline}" for k in missing]
            block[insert_at:insert_at] = additions
        else:
            for key in missing:
                block.append(f"{key} = {set_values[key]}{newline}")

    return "".join(lines[:start] + block + lines[end:])


