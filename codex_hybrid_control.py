def main_with_watchdog(max_restarts: int = 5) -> None:
    """Run the GUI with automatic crash recovery and error logging."""
    for attempt in range(1, max_restarts + 1):
        try:
            _watchdog_log(f"start attempt {attempt}")
            main()
            _watchdog_log("clean exit")
            return
        except KeyboardInterrupt:
            _watchdog_log("interrupted by user")
            return
        except BaseException as exc:
            _watchdog_log(f"crash attempt {attempt}: {type(exc).__name__}: {exc}")
            if attempt >= max_restarts:
                raise
            time.sleep(2.0 * attempt)


if __name__ == "__main__":
    try:
        main_with_watchdog()
    except BaseException as exc:
        _fatal_startup_error(exc)
        raise SystemExit(1)


































