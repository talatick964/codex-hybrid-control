def sanitize_agent_text(text: str) -> str:
    """Remove provider reasoning/interim tokens such as leaked <thinking>/<reasoning> blocks.

    Some gateways emit assistant reasoning prefixes (for example a lone ``Wow`` token
    followed by markdown XML) even when the CLI promises only final agent_message text.
    Those fragments are never user-facing answers, so we strip them defensively while
    keeping the visible answer intact.
    """
    if not text:
        return ""
    value = str(text)
    patterns = [
        r"(?is)\s*<thinking>.*?</thinking>",
        r"(?is)\s*<reasoning>.*?</reasoning>",
        r"(?is)\s*<analysis>.*?</analysis>",
        r"(?is)\s*<thought>.*?</thought>",
    ]
    for pattern in patterns:
        value = re.sub(pattern, "", value)
    # Lone filler tokens occasionally emitted before real output by gateways.
    if value.strip().lower() in {"wow", "ok", "okay", "sure", "嗯"}:
        return ""
    return value.strip()


def _parse_codex_jsonl(raw: str) -> dict:
    """Parse codex exec JSONL into thread id, final answer, errors and tool activity."""
    new_thread = None
    answer_parts: list[str] = []
    errors: list[str] = []
    tools: list[str] = []
    completed = False
    activity = False
    has_events = False
    uncertain = False
    for line in raw.splitlines():
        try:
            ev = json.loads(line)
        except Exception:
            if line.strip(): uncertain = True
            continue
        if not isinstance(ev, dict):
            uncertain = True
            continue
        has_events = True
        event_type = str(ev.get("type") or "")
        if event_type == "turn.completed": completed = True
        if event_type not in {'thread.started','turn.started','turn.completed','turn.failed','error','item.started','item.updated','item.completed'}:
            uncertain = True
        if event_type == "thread.started":
            new_thread = ev.get("thread_id") or new_thread
        if event_type in {"error", "turn.failed"}:
            errors.append(str(ev.get("error") or ev.get("message") or ev)[-2000:])
        item = ev.get("item") if isinstance(ev.get("item"), dict) else {}
        item_type = str(item.get("type") or "")
        if event_type.startswith('item.') and not item_type: uncertain = True
        if item_type and item_type not in {"agent_message", "reasoning", "plan"}: activity = True
        if event_type == "item.completed" and item_type == "agent_message":
            answer_parts.append(str(item.get("text") or ""))
        if item_type in {"tool_call", "command_execution", "mcp_tool_call"} and item.get("name"):
            tools.append(str(item.get("name")))
        if item.get("calls"):
            activity = True
            for call in item.get("calls") or []:
                if isinstance(call, dict) and call.get("name"):
                    tools.append(str(call.get("name")))
    answer = sanitize_agent_text("\n".join(x for x in answer_parts if x).strip())
    return {"thread_id": new_thread, "answer": answer, "errors": errors, "tools": tools,
            "completed": completed, "activity": activity, "has_events": has_events, "uncertain": uncertain}


