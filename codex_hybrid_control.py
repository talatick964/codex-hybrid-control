def _jsonl_tool_evidence(raw: str) -> set[str]:
    """Extract tool names only from JSONL records that look like actual tool-call events.

    This deliberately ignores ordinary user/assistant text so the E2E prompt itself
    cannot satisfy the check merely by containing the strings computer_status or
    computer_screenshot.
    """
    found: set[str] = set()

    def walk(obj):
        if isinstance(obj, dict):
            kind = str(obj.get("type") or "").lower()
            looks_like_tool = ("tool" in kind or "function_call" in kind or "mcp" in kind)
            if looks_like_tool:
                for key in ("tool", "tool_name", "name", "function"):
                    value = obj.get(key)
                    if isinstance(value, str) and value.startswith("computer_"):
                        found.add(value)
            for value in obj.values():
                if isinstance(value, (dict, list)):
                    walk(value)
        elif isinstance(obj, list):
            for value in obj:
                walk(value)

    for line in raw.splitlines():
        try:
            event = json.loads(line)
        except Exception:
            continue
        walk(event)
    return found


