    def _run_background(self, start_message: str, fn, done):
        if self._busy:
            return
        self._busy = True
        self.status.set(start_message)
        self.footer_dot.configure(fg=self.AMBER)
        self.activate_button.configure(state="disabled")

        def worker():
            try:
                result = fn()
                self.after(0, lambda: finish_ok(result))
            except Exception as e:
                self.after(0, lambda: finish_err(e))

        def cleanup():
            self._busy = False
            self.footer_dot.configure(fg=self.GREEN)
            self.activate_button.configure(state="normal")
            self.refresh()

        def finish_ok(result):
            cleanup()
            done(result)

        def finish_err(error):
            cleanup()
            self.status.set(f"ОШИБКА: {error}")
            messagebox.showerror(APP_TITLE, str(error))

        threading.Thread(target=worker, daemon=True).start()

