    def _fit_toplevel(self, win: tk.Toplevel, preferred_w: int, preferred_h: int, min_w: int, min_h: int):
        """Fit child windows to the current monitor so laptop screens do not clip them."""
        screen_w = max(800, win.winfo_screenwidth())
        screen_h = max(600, win.winfo_screenheight())
        safe_min_w = min(min_w, max(680, screen_w - 80))
        safe_min_h = min(min_h, max(460, screen_h - 100))
