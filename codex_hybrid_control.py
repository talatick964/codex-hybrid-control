def validate_api_key(key: str, timeout: int = 15) -> dict:
    from hybrid_http import read_limited
    deadline=time.monotonic()+timeout
    from hybrid_connections import active_connection
    if active_connection(sys.modules[__name__])['base_url'].rstrip('/') != API_BASE + '/v1':
        raise RuntimeError('Статистика Tokify недоступна для этого провайдера. Используйте диагностику API в разделе подключения.')
    body = json.dumps({"key": key}).encode("utf-8")
    req = urllib.request.Request(
        API_BASE + "/public/key-info",
        data=body,
        method="POST",
        headers={"Content-Type": "application/json", "User-Agent": f"CodexHybridControl/{APP_VERSION}"},
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            raw = read_limited(resp,deadline,1_000_000)
    except urllib.error.HTTPError as e:
        if e.code == 400:
            raise ValueError("Gateway отклонил формат токена.") from None
        if e.code == 401:
            raise ValueError("Токен не найден или отключён.") from None
        raise RuntimeError(f"Gateway вернул HTTP {e.code}.") from None
    except urllib.error.URLError as e:
        raise RuntimeError(f"Не удалось подключиться к gateway: {e.reason}") from None
    data = json.loads(raw.decode("utf-8"))
    if not isinstance(data, dict):
        raise ValueError("Gateway вернул некорректный ответ key-info.")
    return data


def _num(value, default=0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return float(default)


def format_tokens(value) -> str:
    n = _num(value, 0)
    if n >= 1_000_000_000:
        return f"{n / 1_000_000_000:.2f}B"
    if n >= 1_000_000:
        return f"{n / 1_000_000:.1f}M"
    if n >= 1_000:
        return f"{n / 1_000:.1f}K"
    return f"{int(n):,}"


def format_int(value) -> str:
    try:
        return f"{int(float(value)):,}"
    except (TypeError, ValueError):
        return "—"


def normalize_key_info(data: dict) -> dict:
    """Normalize Tokify key-info without retaining the secret itself."""
    limits = data.get("limits") if isinstance(data.get("limits"), dict) else {}
    usage = data.get("usage") if isinstance(data.get("usage"), dict) else {}
    quota = data.get("quota") if isinstance(data.get("quota"), dict) else {}

    total = quota.get("total")
    used = quota.get("used")
    remaining = quota.get("remaining")
    if total is not None:
        total_n = _num(total)
        used_n = _num(used) if used is not None else max(0.0, total_n - _num(remaining))
        remaining_n = _num(remaining) if remaining is not None else max(0.0, total_n - used_n)
        pct = (used_n / total_n * 100.0) if total_n > 0 else 0.0
    else:
        total_n = None
        used_n = _num(used) if used is not None else None
        remaining_n = _num(remaining) if remaining is not None else None
        pct = None

    return {
        "label": str(data.get("label") or "API key"),
        "quota_total": total_n,
        "quota_used": used_n,
        "quota_remaining": remaining_n,
        "quota_used_pct": pct,
        "rpm_limit": limits.get("rpm"),
        "rpd_limit": limits.get("rpd"),
        "today_requests": usage.get("today_requests"),
        "total_requests": usage.get("total_requests"),
        "total_tokens": usage.get("total_tokens"),
        "win5h_used": usage.get("win5h_tokens"),
        "win5h_limit": limits.get("win5h_tokens"),
        "month_used": usage.get("month_tokens"),
        "month_limit": limits.get("monthly_tokens"),
        "week_used": usage.get("week_tokens"),
        "week_limit": limits.get("weekly_tokens"),
    }


def _broadcast_environment_change() -> None:
    if os.name != "nt":
        return
    try:
        HWND_BROADCAST = 0xFFFF
        WM_SETTINGCHANGE = 0x001A
        SMTO_ABORTIFHUNG = 0x0002
        result = ctypes.c_ulong()
        ctypes.windll.user32.SendMessageTimeoutW(
            HWND_BROADCAST,
            WM_SETTINGCHANGE,
            0,
            "Environment",
            SMTO_ABORTIFHUNG,
            3000,
            ctypes.byref(result),
        )
    except Exception:
        pass


def _patch_codex_env_secret(key: str | None) -> None:
    """Keep Desktop-compatible FUNPAY_API_KEY in ~/.codex/.env.

    OpenAI documents that Desktop/IDE clients may not inherit shell environment
    variables, so the per-Codex .env is the reliable bridge. The value is never
    surfaced in the UI/logs. On Windows we also tighten the file ACL best-effort.
    """
    path = codex_env_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = ""
    if path.exists():
        existing = path.read_text(encoding="utf-8", errors="ignore")
    lines = existing.splitlines()
    out: list[str] = []
    replaced = False
    for line in lines:
        if re.match(r"^\s*FUNPAY_API_KEY\s*=", line):
            if key is not None:
                out.append(f"FUNPAY_API_KEY={key}")
            replaced = True
        else:
            out.append(line)
    if key is not None and not replaced:
        out.append(f"FUNPAY_API_KEY={key}")
    if out:
        write_text_atomic(path, "\n".join(out).rstrip("\n") + "\n")
    elif path.exists():
        try:
            path.unlink()
        except OSError:
            pass
    if os.name == "nt" and path.exists():
        # Best-effort: disable inheritance and grant current user full control.
        try:
            user = os.environ.get("USERNAME", "").strip()
            if user:
                subprocess.run(
                    ["icacls", str(path), "/inheritance:r", "/grant:r", f"{user}:(F)"],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                    timeout=10,
                    check=False,
                )
        except Exception:
            pass


def set_user_api_key(key: str) -> None:
    from hybrid_connections import validate_key
    key=validate_key(key)
    if os.name != "nt":
        os.environ[API_ENV_KEY] = key
