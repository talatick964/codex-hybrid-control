    def _is_actual_official(self) -> bool:
        return self._actual_info.get("provider") == OFFICIAL_PROVIDER and self._actual_info.get("model") == OFFICIAL_MODEL

    def _selection_is_applied(self) -> bool:
        if not self._actual_info:
            return False
        mode = self.selected_mode.get()
        if mode == "official":
            expected_native = self.delegation_policy.get() == "hybrid"
            delegation_matches = bool(self._actual_info.get("native_agents_enabled", True)) == expected_native
            return self._is_actual_official() and self._actual_info.get("reasoning") == self.reasoning.get() and delegation_matches
        if self._actual_info.get("provider") != API_PROVIDER or self._actual_info.get("model") != self.api_model.get().strip() or self._actual_info.get("reasoning") != self.reasoning.get():
            return False
        if self._actual_info.get("native_agents_enabled", True):
            return False
        policy=computer_policy(); wc,wt,_=self._worker_profile_status()
        return (wc==wt and worker_mcp_installed(self.state_obj.config_path) and worker_instructions_installed() and computer_mcp_installed(self.state_obj.config_path) and computer_instructions_installed() and policy.get("enabled") and policy.get("allow_screenshot") and policy.get("allow_input") and policy.get("allow_launch"))

