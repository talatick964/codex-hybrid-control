    def refresh_api_usage_async(self):
        if self._usage_refreshing:
            return
        token = get_user_api_key()
        if not token:
            self._render_usage_unavailable("НЕТ ТОКЕНА", "warn")
            self.usage_updated_label.configure(text="Нет активного API-токена")
            self._schedule_usage_refresh()
            return
        self._usage_refreshing = True
        self.usage_gateway.configure(text="ПРОВЕРКА…", fg=self.AMBER)

        def worker():
            started = time.perf_counter()
            info = validate_api_key(token, timeout=12)
            return info, int((time.perf_counter() - started) * 1000)

        def finish_ok(info, latency):
            self._usage_refreshing = False
            self._render_usage(info, latency)
            self._schedule_usage_refresh()

        def finish_err(error):
            self._usage_refreshing = False
            self._render_usage_unavailable("ОФЛАЙН / ОШИБКА", "bad")
            self.usage_updated_label.configure(text=f"Ошибка обновления · {datetime.now().strftime('%H:%M:%S')}")
            self.status.set(f"Не удалось обновить использование API: {error}")
            self._schedule_usage_refresh()

        dispatch(self, worker, lambda result: finish_ok(*result), finish_err)

