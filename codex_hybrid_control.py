def apply_mode(config_path: Path, mode: str, api_model: str | None, reasoning: str, delegation_policy: str = "api_only") -> tuple[Path | None, dict]:
    if is_stock_mode():
        raise RuntimeError("Hybrid Control отключён. Сначала восстановите сохранённую настройку.")
    if not config_path.exists():
        ensure_provider_config(config_path)

    original, has_bom = read_text_preserve_bom(config_path)
    parsed_before = validate_toml(original)
    if not isinstance(parsed_before.get("model_providers"), dict) or API_PROVIDER not in parsed_before["model_providers"]:
        original = patch_table_keys(original, "model_providers.funpay", provider_values())
        parsed_before = validate_toml(original)

    if mode == "official":
        values = {
            "model_provider": _toml_string(OFFICIAL_PROVIDER),
            "model": _toml_string(OFFICIAL_MODEL),
            "review_model": _toml_string(OFFICIAL_MODEL),
            "model_reasoning_effort": _toml_string(reasoning),
        }
        updated = edit_root_keys(original, values, remove_keys={"model_catalog_json"})
    elif mode == "api":
        if not api_model:
            raise ValueError("Сначала выбери API-модель.")
        values = {
            "model_provider": _toml_string(API_PROVIDER),
            "model": _toml_string(api_model),
            "review_model": _toml_string(api_model),
            "model_reasoning_effort": _toml_string(reasoning),
            "model_catalog_json": _toml_string(default_catalog_path().as_posix()),
        }
        updated = edit_root_keys(original, values)
    else:
        raise ValueError(f"Неизвестный режим: {mode}")

    if delegation_policy not in {"api_only", "hybrid"}:
        raise ValueError(f"Неизвестная политика делегирования: {delegation_policy}")
    # API-АВТОНОМНЫЙ режим — жёстко API-only. Даже если старое GUI-state
    # говорит hybrid, сторонний provider не должен включать native thread_spawn.
    if mode == "api":
        delegation_policy = "api_only"
    updated = patch_table_keys(updated, "agents", {"enabled": "false" if delegation_policy == "api_only" else "true"})
    updated = patch_table_keys(updated, "model_providers.funpay", provider_values())
    parsed_after = validate_toml(updated)
    backup = backup_config(config_path)
    try:
        write_text_atomic(config_path, updated, has_bom=has_bom)
        disk_text, _ = read_text_preserve_bom(config_path)
        validate_toml(disk_text)
    except Exception:
        if backup:
            shutil.copy2(backup, config_path)
        raise
    cleanup_old_backups(config_path)
    return backup, parsed_after


